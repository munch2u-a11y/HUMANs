WORD_RE = re.compile(r"[a-z0-9]+(?:[._'-][a-z0-9]+)*")


def _session_turns(
    sample: Mapping[str, Any], maximum_sessions: int
) -> list[dict[str, Any]]:
    conversation = sample["conversation"]
    turns: list[dict[str, Any]] = []
    for session in range(1, max(1, int(maximum_sessions)) + 1):
        key = f"session_{session}"
        timestamp = conversation.get(f"{key}_date_time")
        for sequence, raw in enumerate(conversation.get(key, ()) or ()):
            turns.append(
                {
                    **dict(raw),
                    "session": session,
                    "sequence": sequence,
                    "session_date_time": timestamp,
                }
            )
    return turns


def _eligible_questions(
    sample: Mapping[str, Any],
    experienced_ids: set[str],
    *,
    maximum: int,
    categories: Sequence[int],
) -> list[dict[str, Any]]:
    allowed = {int(value) for value in categories}
    eligible = [
        dict(question)
        for question in sample.get("qa", ())
        if question.get("evidence")
        and set(str(value) for value in question["evidence"]).issubset(
            experienced_ids
        )
        and int(question.get("category", -1)) in allowed
    ]
    return eligible[: max(1, int(maximum))]


def _tokens(text: Any) -> list[str]:
    return WORD_RE.findall(str(text).casefold())


def _answer_score(prediction: str, reference: Any) -> dict[str, Any]:
    predicted = _tokens(prediction)
    expected = _tokens(reference)
    overlap = Counter(predicted) & Counter(expected)
    overlap_count = sum(overlap.values())
    precision = overlap_count / len(predicted) if predicted else 0.0
    recall = overlap_count / len(expected) if expected else 0.0
    f1 = (
        2.0 * precision * recall / (precision + recall)
        if precision + recall > 0.0
        else 0.0
    )
    expected_text = " ".join(expected)
    predicted_text = " ".join(predicted)
    return {
        "exact": predicted_text == expected_text,
        "contains_reference": bool(
            expected_text and expected_text in predicted_text
        ),
        "token_precision": precision,
        "token_recall": recall,
        "token_f1": f1,
    }


def _batch_sensations(
    texts: Sequence[str],
    *,
    model: Path,
    codec: Path,
) -> dict[str, LexicalSensation]:
    unique = tuple(
        dict.fromkeys(
            normalized
            for text in texts
            if (normalized := str(text).strip())
        )
    )
    if not unique:
        return {}
    encoded = nursery.tokenize_lexical_sequences(model, codec, unique)
    return {
        text: LexicalSensation(
            input_sha256=hashlib.sha256(text.encode("utf-8")).hexdigest(),
            utterance_embedding=embedding,
            lexical_rows=lexical_rows,
        )
        for text, (_, embedding, lexical_rows) in zip(unique, encoded)
    }


def _count_table(mind: BaseAgenticMemoryRAG, table: str) -> int:
    allowed = {
        "records",
        "concepts",
        "edges",
        "self_pulse_states",
        "self_internal_output_events",
        "experience_cycles",
    }
    if table not in allowed:
        raise ValueError(f"unsupported table: {table}")
    return int(
        mind.store.connection.execute(
            f"SELECT COUNT(*) AS value FROM {table}"
        ).fetchone()["value"]
    )


def _graph_counts(mind: BaseAgenticMemoryRAG) -> dict[str, Any]:
    kinds = Counter(concept.kind for concept in mind.store.list_concepts())
    return {
        "records": _count_table(mind, "records"),
        "concepts": _count_table(mind, "concepts"),
        "edges": _count_table(mind, "edges"),
        "self_pulses": _count_table(mind, "self_pulse_states"),
        "internal_output_events": _count_table(
            mind, "self_internal_output_events"
        ),
        "experience_cycles": _count_table(mind, "experience_cycles"),
        "concept_kinds": dict(sorted(kinds.items())),
        "invariant_errors": list(mind.graph.validate_invariants()),
    }


def _record_dia_id(record: Any) -> str | None:
    value = dict(record.metadata).get("locomo_dia_id")
    return str(value) if value else None


def _turn_metadata(turn: Mapping[str, Any], *, modality: str) -> dict[str, Any]:
    return {
        "locomo_dia_id": str(turn["dia_id"]),
        "locomo_session": int(turn["session"]),
        "locomo_sequence": int(turn["sequence"]),
        "locomo_session_date_time": turn.get("session_date_time"),
        "locomo_modality": modality,
        "developmental_replay": True,
        "teacher_forced": False,
    }


def _growth_row(item: DevelopmentalGrowth) -> dict[str, Any]:
    return {
        "record_ids": list(item.record_ids),
        "input_trunks": [trunk.value for trunk in item.input_trunks],
        "feature_node_ids": list(item.feature_node_ids),
        "candidate_pattern_node_ids": list(item.candidate_pattern_node_ids),
        "promoted_pattern_node_ids": list(item.promoted_pattern_node_ids),
        "active_context_node_ids": list(item.active_context_node_ids),
        "edge_ids": list(item.edge_ids),
        "cross_trunk": item.cross_trunk,
    }


def _checkpoint(mind: BaseAgenticMemoryRAG) -> None:
    mind.store.connection.execute("PRAGMA wal_checkpoint(TRUNCATE)")


def prepare_baseline(
    destination: Path,
    *,
    source_database: Path | None,
    model: Path,
    codec: Path,
    replay_cycles: int,
    promotion_exposures: int,
    transition_promotion_exposures: int,
    maximum_units: int,
) -> dict[str, Any]:
    if source_database is None:
        gestation_manifest = gestation.compile_mind(
            destination,
            model,
            codec,
            human_name="LoCoMo observer",
            agent_name="Habitus",
            taste_schema="curious",
            replay_cycles=replay_cycles,
        )
    else:
        shutil.copy2(source_database, destination)
        gestation_manifest = {
            "reused_database": str(source_database),
            "hatch_ready": None,
        }
    embedder = gestation.NativeMassEmbedder(model, codec)
    with BaseAgenticMemoryRAG(destination, embedder=embedder) as mind:
        embedder.bootstrap = False
        desires = desire_nursery.install_desire_nursery(mind, model, codec)
        DevelopmentalLanguage(
            mind,
            promotion_exposures=promotion_exposures,
            transition_promotion_exposures=transition_promotion_exposures,
            maximum_units=maximum_units,
        )
        SelfPulseKernel(mind)
        counts = _graph_counts(mind)
        _checkpoint(mind)
    return {
        "gestation": gestation_manifest,
        "desire_nursery_ready": bool(desires["ready"]),
        "counts": counts,
    }


def ingest_development(
    database: Path,
    *,
    turns: Sequence[Mapping[str, Any]],
    model: Path,
    codec: Path,
    include_images: bool,
    batch_size: int,
    promotion_exposures: int,
    transition_promotion_exposures: int,
    maximum_units: int,
    progress: bool,
) -> dict[str, Any]:
    embedder = gestation.NativeMassEmbedder(model, codec)
    trace: list[dict[str, Any]] = []
    modality_counts: Counter[str] = Counter()
    growth_receipts = 0
    feature_ids: set[str] = set()
    candidate_pattern_ids: set[str] = set()
    promoted_pattern_ids: set[str] = set()
    cross_trunk_receipts = 0
    with BaseAgenticMemoryRAG(database, embedder=embedder) as mind:
        embedder.bootstrap = False
        language = DevelopmentalLanguage(
            mind,
            promotion_exposures=promotion_exposures,
            transition_promotion_exposures=transition_promotion_exposures,
            maximum_units=maximum_units,
        )
        planner = NoContextPlanner(
            mind,
            lexical_sensor=lambda _text: (),
            language_learner=language,
        )
        before = _graph_counts(mind)
        consolidation = language.consolidate_ready_patterns()
        resumed_turns = 0
        new_turns = 0
        resolved_batch = max(1, int(batch_size))
        for start in range(0, len(turns), resolved_batch):
            batch = turns[start : start + resolved_batch]
            uncached_batch = [
                turn
                for turn in batch
                if mind.store.get_record(
                    "self-pulse-record:locomo:hear:" + str(turn["dia_id"])
                )
                is None
            ]
            forms = [str(turn["text"]).strip() for turn in uncached_batch]
            if include_images:
                forms.extend(
                    str(turn["blip_caption"])
                    for turn in uncached_batch
                    if str(turn.get("blip_caption") or "").strip()
                )
            sensations = _batch_sensations(forms, model=model, codec=codec)
            for offset, turn in enumerate(batch):
                index = start + offset
                if progress and index % 10 == 0:
                    print(
                        f"development: turn {index + 1}/{len(turns)}",
                        file=sys.stderr,
                        flush=True,
                    )
                dia_id = str(turn["dia_id"])
                modality_counts["HEAR"] += 1
                if int(turn["sequence"]) == 0:
                    modality_counts["NOTICE"] += 1
                caption = str(turn.get("blip_caption") or "").strip()
                if include_images and caption:
                    modality_counts["SEE"] += 1

                hear_item_id = f"locomo:hear:{dia_id}"
                existing_record = mind.store.get_record(
                    f"self-pulse-record:{hear_item_id}"
                )
                if existing_record is not None:
                    inbox = mind.store.connection.execute(
                        """SELECT processed_pulse FROM self_pulse_inbox
                           WHERE item_id = ?""",
                        (hear_item_id,),
                    ).fetchone()
                    processed_pulse = (
                        int(inbox["processed_pulse"])
                        if inbox is not None and inbox["processed_pulse"] is not None
                        else None
                    )
                    state = (
                        mind.store.connection.execute(
                            """SELECT state_sha256 FROM self_pulse_states
                               WHERE pulse = ?""",
                            (processed_pulse,),
                        ).fetchone()
                        if processed_pulse is not None
                        else None
                    )
                    trace.append(
                        {
                            "index": index,
                            "dia_id": dia_id,
                            "speaker": str(turn["speaker"]),
                            "pulse": processed_pulse,
                            "state_sha256": (
                                state["state_sha256"] if state is not None else None
                            ),
                            "resumed_from_checkpoint": True,
                            "input_record_id": existing_record.record_id,
                        }
                    )
                    resumed_turns += 1
                    continue

                extras = []
                if int(turn["sequence"]) == 0:
                    notice = planner.pulse_kernel.enqueue_input(
                        f"session:{int(turn['session'])}",
                        lane=InputTrunk.NOTICE,
                        source_id="locomo-session-clock",
                        embedding=[0.0] * mind.embedder.dimension,
                        item_id=f"locomo:notice:{int(turn['session'])}",
                        metadata={
                            "locomo_session": int(turn["session"]),
                            "locomo_session_date_time": turn.get(
                                "session_date_time"
                            ),
                            "locomo_modality": "session_boundary",
                            "developmental_replay": True,
                        },
                    )
                    extras.append(notice.item_id)

                if include_images and caption:
                    visual = sensations[caption]
                    candidates = planner._input_candidates(
                        visual.utterance_embedding,
                        input_trunk=InputTrunk.SEE,
                    )
                    seen_item_id = f"locomo:see:{dia_id}"
                    existing_seen = mind.store.connection.execute(
                        """SELECT status FROM self_pulse_inbox
                           WHERE item_id = ?""",
                        (seen_item_id,),
                    ).fetchone()
                    if existing_seen is None:
                        seen = planner.pulse_kernel.enqueue_input(
                            caption,
                            lane=InputTrunk.SEE,
                            source_id=str(turn["speaker"]),
                            concept_ids=tuple(item[1] for item in candidates),
                            concept_scores={
                                node_id: max(0.0, min(1.0, score))
                                for score, node_id, _ in candidates
                            },
                            embedding=visual.utterance_embedding,
                            item_id=seen_item_id,
                            metadata=_turn_metadata(
                                turn, modality="image_caption"
                            ),
                        )
                        extras.append(seen.item_id)
                    elif existing_seen["status"] == "pending":
                        extras.append(seen_item_id)
                    else:
                        raise RuntimeError(
                            f"incomplete turn has unusable SEE item: {seen_item_id}"
                        )

                text = str(turn["text"]).strip()
                sensation = sensations[text]
                plan = planner.hear(
                    text,
                    source_id=str(turn["speaker"]),
                    sensation=sensation,
                    additional_input_item_ids=tuple(extras),
                    input_item_id=hear_item_id,
                    input_metadata=_turn_metadata(turn, modality="utterance"),
                )
                growth_rows = [
                    _growth_row(item) for item in plan.developmental_growth
                ]
                growth_receipts += len(plan.developmental_growth)
                cross_trunk_receipts += sum(
                    item.cross_trunk for item in plan.developmental_growth
                )
                for item in plan.developmental_growth:
                    feature_ids.update(item.feature_node_ids)
                    candidate_pattern_ids.update(item.candidate_pattern_node_ids)
                    promoted_pattern_ids.update(item.promoted_pattern_node_ids)
                new_turns += 1
                trace.append(
                    {
                        "index": index,
                        "dia_id": dia_id,
                        "speaker": str(turn["speaker"]),
                        "pulse": plan.self_pulse.self_state.pulse,
                        "state_sha256": plan.self_pulse.self_state.state_sha256,
                        "settled_order": [
                            lane.value
                            for lane in plan.self_pulse.self_state.settled_order
                        ],
                        "input_item_ids": list(
                            plan.self_pulse.self_state.input_item_ids
                        ),
                        "input_record_id": plan.input_record.record_id,
                        "selected_output_trunk": (
                            plan.focus.selected.trunk.value
                            if plan.focus.selected is not None
                            else None
                        ),
                        "selected_output_node_id": (
                            plan.focus.selected.terminal_node_id
                            if plan.focus.selected is not None
                            else None
                        ),
                        "developmental_growth": growth_rows,
                    }
                )
        after = _graph_counts(mind)
        pending = [item.item_id for item in planner.pulse_kernel.pending()]
        _checkpoint(mind)
    return {
        "observer_mode": True,
        "teacher_forced_outputs": 0,
        "turns": len(turns),
        "turns_resumed_from_checkpoint": resumed_turns,
        "turns_newly_processed": new_turns,
        "modality_counts": dict(sorted(modality_counts.items())),
        "developmental_growth": {
            "receipts": growth_receipts,
            "cross_trunk_receipts": cross_trunk_receipts,
            "unique_feature_nodes": len(feature_ids),
            "unique_candidate_patterns_observed": len(candidate_pattern_ids),
            "unique_promoted_patterns_observed": len(promoted_pattern_ids),
        },
        "restart_consolidation": {
            key: list(value) for key, value in consolidation.items()
        },
        "before": before,
        "after": after,
        "pending_input_item_ids": pending,
        "new_invariant_errors": sorted(
            set(after["invariant_errors"]) - set(before["invariant_errors"])
        ),
        "trace": trace,
    }


def _retrieval_diagnostic(
    mind: BaseAgenticMemoryRAG,
    question: str,
    expected_evidence_ids: Sequence[str],
) -> dict[str, Any]:
    recall = mind.recall(question, include_current_input=False)
    hits = []
    for hit in recall.hits:
        dia_id = _record_dia_id(hit.record)
        if dia_id is None:
            continue
        hits.append(
            {
                "record_id": hit.record.record_id,
                "dia_id": dia_id,
                "dense_score": hit.dense_score,
                "lexical_score": hit.lexical_score,
                "path_score": hit.path_score,
                "text": hit.record.text,
            }
        )
    recalled = [str(hit["dia_id"]) for hit in hits]
    expected = [str(value) for value in expected_evidence_ids]
    ranks = {
        dia_id: recalled.index(dia_id) + 1
        for dia_id in expected
        if dia_id in recalled
    }

    def all_at(cutoff: int) -> bool:
        return bool(expected) and all(
            ranks.get(dia_id, cutoff + 1) <= cutoff for dia_id in expected
        )

    return {
        "expected_evidence_ids": expected,
        "recalled_evidence_ids": recalled,
        "evidence_ranks": ranks,
        "any_evidence_recalled": bool(set(expected) & set(recalled)),
        "all_evidence_recalled": set(expected).issubset(recalled),
        "all_evidence_at_5": all_at(5),
        "all_evidence_at_10": all_at(10),
        "hits": hits,
    }


def probe_question(
    source_database: Path,
    destination: Path,
    *,
    condition: str,
    index: int,
    question: str,
    expected_evidence_ids: Sequence[str],
    sensation: LexicalSensation,
    model: Path,
    codec: Path,
    runner: Path,
    with_native_continuation: bool,
    maximum_tokens: int,
    minimum_words: int,
    maximum_words: int,
    seed: int,
    promotion_exposures: int,
    transition_promotion_exposures: int,
    maximum_units: int,
) -> dict[str, Any]:
    shutil.copy2(source_database, destination)
    embedder = gestation.NativeMassEmbedder(model, codec)
    embedder.cache[question] = sensation.utterance_embedding
    packet_path = destination.with_suffix(".packet")
    with BaseAgenticMemoryRAG(destination, embedder=embedder) as mind:
        embedder.bootstrap = False
        language = DevelopmentalLanguage(
            mind,
            promotion_exposures=promotion_exposures,
            transition_promotion_exposures=transition_promotion_exposures,
            maximum_units=maximum_units,
        )
        planner = NoContextPlanner(
            mind,
            lexical_sensor=lambda _text: sensation.lexical_rows,
            language_learner=language,
        )
        plan = planner.hear(
            question,
            source_id="locomo-examiner",
            sensation=sensation,
            input_item_id=f"locomo:question:{condition}:{index}",
            input_metadata={
                "held_out_question": True,
                "evaluation_condition": condition,
            },
        )
        selected = plan.focus.selected
        result: dict[str, Any] = {
            "condition": condition,
            "question_input_record_id": plan.input_record.record_id,
            "self_pulse": {
                "pulse": plan.self_pulse.self_state.pulse,
                "state_sha256": plan.self_pulse.self_state.state_sha256,
                "settled_order": [
                    lane.value for lane in plan.self_pulse.self_state.settled_order
                ],
                "input_item_ids": list(
                    plan.self_pulse.self_state.input_item_ids
                ),
            },
            "selected_output": (
                {
                    "trunk": selected.trunk.value,
                    "node_id": selected.terminal_node_id,
                    "path_node_ids": list(selected.path_node_ids),
                    "authorization_id": plan.output_authorization_id,
                }
                if selected is not None
                else None
            ),
            "productive_surface": "",
            "native_continuation": "",
            "response": "",
            "generated": False,
            "generation_error": None,
        }
        if selected is None or selected.trunk != OutputTrunk.SPEAK:
            result["generation_error"] = "SELF did not select SPEAK"
        else:
            try:
                speech = planner.compose_speech(
                    plan,
                    minimum_words=minimum_words,
                    maximum_words=maximum_words,
                )
                productive, decode = decode_productive_surface(
                    speech, model=model, codec=codec
                )
                continuation = ""
                native = None
                if with_native_continuation:
                    write_native_state_packet(packet_path, speech.frame)
                    native = run_native(
                        model,
                        runner,
                        packet_path,
                        maximum_tokens=maximum_tokens,
                        seed=seed + index,
                        skip_think=True,
                    )
                    continuation = _novel_continuation(
                        str(native.get("response", "")), productive
                    )
                response = " ".join(
                    part for part in (productive, continuation) if part
                ).strip()
                result.update(
                    {
                        "productive_surface": productive,
                        "productive_decode": decode,
                        "native_continuation": continuation,
                        "native": native,
                        "response": response,
                        "generated": bool(response),
                        "lexical_node_ids": list(speech.lexical_node_ids),
                        "lexical_steps": len(speech.steps),
                    }
                )
                if response:
                    cycle = planner.begin_speech_cycle(
                        plan, response, speech=speech
                    )
                    result["output_cycle_id"] = cycle.cycle_id
            except Exception as error:
                result["generation_error"] = (
                    f"{type(error).__name__}: {error}"
                )

        # Deliberately run after generation.  These hits diagnose canonical
        # memory accessibility; neither hit text nor IDs can influence speech.
        result["retrieval"] = _retrieval_diagnostic(
            mind, question, expected_evidence_ids
        )
        result["post_probe_counts"] = _graph_counts(mind)
        _checkpoint(mind)
        return result


def _aggregate(results: Sequence[Mapping[str, Any]], condition: str) -> dict[str, Any]:
    selected = [result[condition] for result in results]
    count = len(selected)
    generated = [item for item in selected if item["generated"]]
    return {
        "questions": count,
        "speech_selected": sum(
            bool(item.get("selected_output"))
            and item["selected_output"]["trunk"] == OutputTrunk.SPEAK.value
            for item in selected
        ),
        "generated_answers": len(generated),
        "exact_answers": sum(item["answer_score"]["exact"] for item in selected),
        "answers_containing_reference": sum(
            item["answer_score"]["contains_reference"] for item in selected
        ),
        "answers_with_token_overlap": sum(
            item["answer_score"]["token_f1"] > 0.0 for item in selected
        ),
        "mean_token_f1": (
            sum(item["answer_score"]["token_f1"] for item in selected) / count
            if count
            else 0.0
        ),
        "any_evidence_recall": sum(
            item["retrieval"]["any_evidence_recalled"] for item in selected
        ),
        "full_evidence_recall": sum(
            item["retrieval"]["all_evidence_recalled"] for item in selected
        ),
        "full_evidence_recall_at_5": sum(
            item["retrieval"]["all_evidence_at_5"] for item in selected
        ),
        "full_evidence_recall_at_10": sum(
            item["retrieval"]["all_evidence_at_10"] for item in selected
        ),
    }


def run_trial(args: argparse.Namespace) -> dict[str, Any]:
    started = time.monotonic()
    data = json.loads(args.dataset.read_text(encoding="utf-8"))
    sample = data[args.conversation]
    turns = _session_turns(sample, args.sessions)
    experienced_ids = {str(turn["dia_id"]) for turn in turns}
    questions = _eligible_questions(
        sample,
        experienced_ids,
        maximum=args.questions,
        categories=args.categories,
    )
    if not turns or not questions:
        raise RuntimeError("selected LoCoMo slice has no turns or eligible questions")

    run_directory = args.output / str(time.time_ns())
    run_directory.mkdir(parents=True)
    baseline_database = run_directory / "baseline.sqlite"
    trained_database = run_directory / "trained.sqlite"
    phase_started = time.monotonic()
    baseline = prepare_baseline(
        baseline_database,
        source_database=args.base_database,
        model=args.model,
        codec=args.codec,
        replay_cycles=args.replay_cycles,
        promotion_exposures=args.lexeme_promotion_exposures,
        transition_promotion_exposures=args.transition_promotion_exposures,
        maximum_units=args.maximum_heard_units,
    )
    baseline_seconds = time.monotonic() - phase_started
    shutil.copy2(
        args.resume_trained_database or baseline_database,
        trained_database,
    )
    phase_started = time.monotonic()
    development = ingest_development(
        trained_database,
        turns=turns,
        model=args.model,
        codec=args.codec,
        include_images=args.include_images,
        batch_size=args.batch_size,
        promotion_exposures=args.lexeme_promotion_exposures,
        transition_promotion_exposures=args.transition_promotion_exposures,
        maximum_units=args.maximum_heard_units,
        progress=not args.quiet,
    )
    development_seconds = time.monotonic() - phase_started

    phase_started = time.monotonic()
    question_sensations = _batch_sensations(
        [str(question["question"]) for question in questions],
        model=args.model,
        codec=args.codec,
    )
    question_sensing_seconds = time.monotonic() - phase_started
    probe_directory = run_directory / "probes"
    probe_directory.mkdir()
    results = []
    phase_started = time.monotonic()
    for index, question in enumerate(questions):
        if not args.quiet:
            print(
                f"probe: question {index + 1}/{len(questions)}",
                file=sys.stderr,
                flush=True,
            )
        text = str(question["question"])
        expected_ids = tuple(str(value) for value in question["evidence"])
        conditions = {}
        for condition, source in (
            ("baseline", baseline_database),
            ("trained", trained_database),
        ):
            conditions[condition] = probe_question(
                source,
                probe_directory / f"question-{index:03d}-{condition}.sqlite",
                condition=condition,
                index=index,
                question=text,
                expected_evidence_ids=expected_ids,
                sensation=question_sensations[text],
                model=args.model,
                codec=args.codec,
                runner=args.runner,
                with_native_continuation=args.with_native_continuation,
                maximum_tokens=args.maximum_tokens,
                minimum_words=args.minimum_words,
                maximum_words=args.maximum_words,
                seed=args.seed,
                promotion_exposures=args.lexeme_promotion_exposures,
                transition_promotion_exposures=(
                    args.transition_promotion_exposures
                ),
                maximum_units=args.maximum_heard_units,
            )
            conditions[condition]["answer_score"] = _answer_score(
                conditions[condition]["response"], question["answer"]
            )
        results.append(
            {
                "question": text,
                "reference_answer": question["answer"],
                "category": int(question.get("category", -1)),
                "evidence": list(expected_ids),
                **conditions,
            }
        )
    probe_seconds = time.monotonic() - phase_started
    elapsed_seconds = time.monotonic() - started

    report = {
        "schema": "habitus.locomo-self-pulse-trial.v2",
        "claim_boundary": {
            "bulk_ingestion_used": False,
            "turn_order_preserved": True,
            "session_boundaries_enter_notice": True,
            "image_captions_enter_see": bool(args.include_images),
            "utterances_enter_hear": True,
            "developmental_growth_starts_at_input_trunks": True,
            "record_text_used_to_name_experiential_nodes": False,
            "corpus_speech_teacher_forced": False,
            "questions_seen_during_development": False,
            "reference_answers_seen_during_development": False,
            "transcript_or_recalled_text_sent_to_language_surface": False,
            "retrieval_measured_after_generation": True,
            "baseline_and_trained_probes_isolated": True,
            "native_continuation_enabled": bool(
                args.with_native_continuation
            ),
        },
        "dataset": str(args.dataset),
        "conversation": args.conversation,
        "sample_id": sample.get("sample_id"),
        "sessions": args.sessions,
        "speakers": [
            sample["conversation"].get("speaker_a"),
            sample["conversation"].get("speaker_b"),
        ],
        "turns": len(turns),
        "categories": list(args.categories),
        "elapsed_seconds": elapsed_seconds,
        "phase_seconds": {
            "baseline_preparation": baseline_seconds,
            "developmental_replay": development_seconds,
            "question_sensing": question_sensing_seconds,
            "isolated_probes": probe_seconds,
            "other": max(
                0.0,
                elapsed_seconds
                - baseline_seconds
                - development_seconds
                - question_sensing_seconds
                - probe_seconds,
            ),
        },
        "baseline_database": str(baseline_database),
        "trained_database": str(trained_database),
        "resumed_trained_database": (
            str(args.resume_trained_database)
            if args.resume_trained_database is not None
            else None
        ),
        "baseline": baseline,
        "development": development,
        "questions": results,
        "metrics": {
            "baseline": _aggregate(results, "baseline"),
            "trained": _aggregate(results, "trained"),
            "trained_f1_improvements": sum(
                item["trained"]["answer_score"]["token_f1"]
                > item["baseline"]["answer_score"]["token_f1"]
                for item in results
            ),
        },
    }
    receipt_path = run_directory / "receipt.json"
    report["receipt_path"] = str(receipt_path)
    receipt_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return report


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--base-database", type=Path)
    parser.add_argument("--resume-trained-database", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--model", type=Path, default=nursery.MODEL)
    parser.add_argument("--codec", type=Path, default=nursery.CODEC)
    parser.add_argument("--runner", type=Path, default=DEFAULT_RUNNER)
    parser.add_argument("--conversation", type=int, default=0)
    parser.add_argument("--sessions", type=int, default=5)
    parser.add_argument("--questions", type=int, default=8)
    parser.add_argument("--categories", type=int, nargs="+", default=(1,))
    parser.add_argument("--replay-cycles", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=12)
    parser.add_argument("--lexeme-promotion-exposures", type=int, default=3)
    parser.add_argument("--transition-promotion-exposures", type=int, default=3)
    parser.add_argument("--maximum-heard-units", type=int, default=64)
    parser.add_argument("--minimum-words", type=int, default=1)
    parser.add_argument("--maximum-words", type=int, default=12)
    parser.add_argument("--maximum-tokens", type=int, default=48)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--include-images",
        action=argparse.BooleanOptionalAction,
        default=True,
    )
    parser.add_argument("--with-native-continuation", action="store_true")
    parser.add_argument("--quiet", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    required = [args.dataset, args.model, args.codec]
    if args.base_database is not None:
        required.append(args.base_database)
    if args.resume_trained_database is not None:
        required.append(args.resume_trained_database)
    if args.with_native_continuation:
        required.append(args.runner)
    for artifact in required:
        if not artifact.is_file():
            raise SystemExit(f"required artifact not found: {artifact}")
    if args.sessions < 1 or args.questions < 1:
        raise SystemExit("sessions and questions must be positive")
    report = run_trial(args)
    print(
        json.dumps(
            {
                "receipt": report["receipt_path"],
                "turns": report["turns"],
                "metrics": report["metrics"],
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
