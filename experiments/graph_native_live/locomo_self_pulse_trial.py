#!/usr/bin/env python3
"""Replay LoCoMo as lived SELF pulses, then run held-out no-context QA.

This is deliberately not a bulk-ingestion RAG benchmark.  Conversation turns
arrive chronologically through HEAR, session boundaries arrive through NOTICE,
and available image captions arrive through SEE in the same bounded frame.
Both speakers are observed as external sources; no corpus utterance is falsely
claimed as speech generated by Habitus.

Each held-out question is tested against an untouched nursery baseline and an
independent copy of the replayed mind.  The answer surface is selected from the
live recurrent graph without a transcript or recalled text.  Ordinary retrieval
is measured only afterward as a separate diagnostic and is never supplied to
the language surface.
"""

